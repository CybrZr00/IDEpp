using System.Reflection.PortableExecutable;
using System.Text;

namespace IdePlusPlus.ReverseEngineering;

/// <summary>What a generated shim produced: the primary file, all files written, and the count forwarded.</summary>
public sealed record ShimResult(string PrimaryPath, IReadOnlyList<string> Files, int ForwardedCount);

/// <summary>
/// Generates a forwarding shim. For a managed assembly: a .csproj plus a Forwarders.cs of
/// <c>[assembly: TypeForwardedTo(...)]</c> for every public top-level type. For a native binary: a
/// .def that forwards every named export to the original module. Either way it automates the tedious,
/// error-prone enumeration of hand-writing a shim.
/// </summary>
public sealed class ShimGenerator
{
    private readonly ManagedDecompiler _decompiler;

    public ShimGenerator(ManagedDecompiler? decompiler = null) => _decompiler = decompiler ?? new ManagedDecompiler();

    /// <summary>Detects whether the target is a managed assembly or a native binary and generates the
    /// matching shim.</summary>
    public ShimResult GenerateForwarder(string path, string outputDirectory) =>
        IsManaged(path) ? GenerateManagedForwarder(path, outputDirectory) : GenerateNativeForwarder(path, outputDirectory);

    public ShimResult GenerateManagedForwarder(string assemblyPath, string outputDirectory)
    {
        var name = Path.GetFileNameWithoutExtension(assemblyPath);
        var types = _decompiler.GetForwardableTypes(assemblyPath);

        Directory.CreateDirectory(outputDirectory);
        var forwardersPath = Path.Combine(outputDirectory, "Forwarders.cs");
        var projectPath = Path.Combine(outputDirectory, $"{name}.Shim.csproj");
        var readmePath = Path.Combine(outputDirectory, "README.md");

        File.WriteAllText(forwardersPath, BuildForwarders(types));
        File.WriteAllText(projectPath, BuildProject(name, assemblyPath));
        File.WriteAllText(readmePath, BuildReadme(name, assemblyPath, types.Count));

        return new ShimResult(projectPath, [projectPath, forwardersPath, readmePath], types.Count);
    }

    public ShimResult GenerateNativeForwarder(string binaryPath, string outputDirectory)
    {
        var name = Path.GetFileNameWithoutExtension(binaryPath);
        var exports = NativeExportReader.Read(binaryPath);
        var forwardModule = $"{name}_orig";

        Directory.CreateDirectory(outputDirectory);
        var defPath = Path.Combine(outputDirectory, $"{name}.def");
        var readmePath = Path.Combine(outputDirectory, "README.md");

        File.WriteAllText(defPath, BuildDef(name, exports, forwardModule));
        File.WriteAllText(readmePath, BuildNativeReadme(name, binaryPath, exports, forwardModule));

        return new ShimResult(defPath, [defPath, readmePath], exports.Names.Count);
    }

    private static bool IsManaged(string path)
    {
        using var stream = File.OpenRead(path);
        using var peReader = new PEReader(stream);
        try
        {
            return peReader.HasMetadata;
        }
        catch (BadImageFormatException)
        {
            return false;
        }
    }

    private static string BuildForwarders(IReadOnlyList<ForwardableType> types)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// Generated by IDE++. Each line forwards a public type to the original assembly.");
        builder.AppendLine("using System.Runtime.CompilerServices;");
        builder.AppendLine();

        foreach (var type in types.OrderBy(t => t.Namespace, StringComparer.Ordinal).ThenBy(t => t.Name, StringComparer.Ordinal))
        {
            var fullName = string.IsNullOrEmpty(type.Namespace) ? type.Name : $"{type.Namespace}.{type.Name}";
            var generic = type.Arity > 0 ? "<" + new string(',', type.Arity - 1) + ">" : "";
            builder.AppendLine($"[assembly: TypeForwardedTo(typeof(global::{fullName}{generic}))]");
        }

        return builder.ToString();
    }

    private static string BuildProject(string name, string originalPath) =>
        $"""
        <Project Sdk="Microsoft.NET.Sdk">

          <PropertyGroup>
            <TargetFramework>net8.0</TargetFramework>
            <!-- The facade carries the original's simple name so consumers bind to it unchanged. -->
            <AssemblyName>{name}</AssemblyName>
            <Nullable>disable</Nullable>
          </PropertyGroup>

          <ItemGroup>
            <!-- The assembly that actually holds the types. See README.md for the deployment caveat. -->
            <Reference Include="{name}.Original">
              <HintPath>{originalPath}</HintPath>
            </Reference>
          </ItemGroup>

        </Project>

        """;

    private static string BuildReadme(string name, string originalPath, int typeCount) =>
        $"""
        # {name} shim

        A type-forwarding facade generated by IDE++ for `{originalPath}`.

        `Forwarders.cs` forwards {typeCount} public top-level type(s) to the original assembly via
        `[assembly: TypeForwardedTo(...)]`. Build this project to produce a `{name}.dll` that contains
        only forwarders.

        ## Deployment caveat

        The facade and the original assembly share the simple name `{name}`, so they cannot sit in the
        same folder under that name. Deploy the original under its own identity (a different folder, or
        renamed) and let the forwards resolve to it. The `HintPath` here points at the original only so
        the project compiles.
        """;

    private static string BuildDef(string name, NativeExports exports, string forwardModule)
    {
        var builder = new StringBuilder();
        builder.AppendLine($"; Generated by IDE++ - forwards {name}'s exports to {forwardModule}.dll.");
        builder.AppendLine($"LIBRARY {name}");
        builder.AppendLine("EXPORTS");
        foreach (var export in exports.Names)
        {
            builder.AppendLine($"    {export} = {forwardModule}.{export}");
        }

        return builder.ToString();
    }

    private static string BuildNativeReadme(string name, string originalPath, NativeExports exports, string forwardModule) =>
        $"""
        # {name} shim

        A forwarding shim generated by IDE++ for `{originalPath}`.

        `{name}.def` forwards {exports.Names.Count} named export(s) to `{forwardModule}.dll` (the original
        module `{exports.ModuleName}`, deployed under the name `{forwardModule}.dll`).

        ## Building

        Link the .def into a stub DLL, e.g.:

            link /DLL /NOENTRY /DEF:{name}.def /OUT:{name}.dll /MACHINE:X64

        Then deploy the original binary as `{forwardModule}.dll` beside the generated `{name}.dll`.
        Calls into `{name}.dll` forward to it. Exports that have only an ordinal (no name) are not
        forwarded, since a .def forwards by name.
        """;
}
