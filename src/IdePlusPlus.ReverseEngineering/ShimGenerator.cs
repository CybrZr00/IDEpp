using System.Text;

namespace IdePlusPlus.ReverseEngineering;

/// <summary>What a generated shim produced: the files and how many types were forwarded.</summary>
public sealed record ShimResult(string ProjectPath, string ForwardersPath, string ReadmePath, int ForwardedTypeCount);

/// <summary>
/// Generates a type-forwarding facade for a managed assembly: a small project whose only content is
/// <c>[assembly: TypeForwardedTo(...)]</c> for every public top-level type, so a consumer can bind to
/// the facade while the real types live in the original assembly. This is the tedious, error-prone
/// part of hand-writing a shim (enumerating every type, getting generic arity right) done for you.
/// </summary>
public sealed class ShimGenerator
{
    private readonly ManagedDecompiler _decompiler;

    public ShimGenerator(ManagedDecompiler? decompiler = null) => _decompiler = decompiler ?? new ManagedDecompiler();

    public ShimResult GenerateManagedForwarder(string assemblyPath, string outputDirectory)
    {
        var name = Path.GetFileNameWithoutExtension(assemblyPath);
        var types = _decompiler.GetForwardableTypes(assemblyPath);

        Directory.CreateDirectory(outputDirectory);
        var forwardersPath = Path.Combine(outputDirectory, "Forwarders.cs");
        var projectPath = Path.Combine(outputDirectory, $"{name}.Shim.csproj");
        var readmePath = Path.Combine(outputDirectory, "README.md");

        File.WriteAllText(forwardersPath, BuildForwarders(types));
        File.WriteAllText(projectPath, BuildProject(name, assemblyPath));
        File.WriteAllText(readmePath, BuildReadme(name, assemblyPath, types.Count));

        return new ShimResult(projectPath, forwardersPath, readmePath, types.Count);
    }

    private static string BuildForwarders(IReadOnlyList<ForwardableType> types)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// Generated by IDE++. Each line forwards a public type to the original assembly.");
        builder.AppendLine("using System.Runtime.CompilerServices;");
        builder.AppendLine();

        foreach (var type in types.OrderBy(t => t.Namespace, StringComparer.Ordinal).ThenBy(t => t.Name, StringComparer.Ordinal))
        {
            var fullName = string.IsNullOrEmpty(type.Namespace) ? type.Name : $"{type.Namespace}.{type.Name}";
            var generic = type.Arity > 0 ? "<" + new string(',', type.Arity - 1) + ">" : "";
            builder.AppendLine($"[assembly: TypeForwardedTo(typeof(global::{fullName}{generic}))]");
        }

        return builder.ToString();
    }

    private static string BuildProject(string name, string originalPath) =>
        $"""
        <Project Sdk="Microsoft.NET.Sdk">

          <PropertyGroup>
            <TargetFramework>net8.0</TargetFramework>
            <!-- The facade carries the original's simple name so consumers bind to it unchanged. -->
            <AssemblyName>{name}</AssemblyName>
            <Nullable>disable</Nullable>
          </PropertyGroup>

          <ItemGroup>
            <!-- The assembly that actually holds the types. See README.md for the deployment caveat. -->
            <Reference Include="{name}.Original">
              <HintPath>{originalPath}</HintPath>
            </Reference>
          </ItemGroup>

        </Project>

        """;

    private static string BuildReadme(string name, string originalPath, int typeCount) =>
        $"""
        # {name} shim

        A type-forwarding facade generated by IDE++ for `{originalPath}`.

        `Forwarders.cs` forwards {typeCount} public top-level type(s) to the original assembly via
        `[assembly: TypeForwardedTo(...)]`. Build this project to produce a `{name}.dll` that contains
        only forwarders.

        ## Deployment caveat

        The facade and the original assembly share the simple name `{name}`, so they cannot sit in the
        same folder under that name. Deploy the original under its own identity (a different folder, or
        renamed) and let the forwards resolve to it. The `HintPath` here points at the original only so
        the project compiles.
        """;
}
